"""Signal Engine.

Translates semantic MethodologyEvaluations into actionable Trade Signals.
"""

from typing import List
import logging
from Backend.methodology.evaluation import MethodologyEvaluation
from Backend.methodology.signals import MethodologySignal
from Shared.enums.signal_direction import SignalDirection

logger = logging.getLogger(__name__)


class SignalEngine:
    """
    Translates Methodology Evaluations into discrete Trading Signals.
    Enforces rules mapping evaluation vectors to Long/Short/Wait states.
    """

    def process(self, evaluations: List[MethodologyEvaluation]) -> List[MethodologySignal]:
        """
        Processes evaluations into Signals.

        Args:
            evaluations: List of active evaluations from the Methodology Engine.

        Returns:
            A list of actionable Signals.
        """
        signals = []
        for eval_data in evaluations:
            try:
                if not eval_data.is_active:
                    continue

                if eval_data.direction == 1:
                    direction_str = SignalDirection.LONG
                elif eval_data.direction == -1:
                    direction_str = SignalDirection.SHORT
                else:
                    direction_str = SignalDirection.WAIT

                if direction_str != SignalDirection.WAIT:
                    sig = MethodologySignal(
                        direction=direction_str,
                        confidence=eval_data.confidence,
                        strength=eval_data.confidence,  # Map strength natively for now
                        reason=f"Generated by {eval_data.methodology_id} at {eval_data.timestamp}",
                        concept_ids=list(eval_data.supporting_concepts.keys()),
                        methodology=eval_data.methodology_id,
                        provider="SignalEngine"
                    )
                    signals.append(sig)
            except Exception as e:
                logger.error("Signal Engine failed to process evaluation from %s: %s", eval_data.methodology_id, e)

        return signals
