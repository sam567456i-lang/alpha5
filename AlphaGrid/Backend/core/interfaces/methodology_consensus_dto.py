from dataclasses import dataclass, field
from typing import List, Dict

@dataclass(frozen=True)
class MethodologyConsensusDTO:
    """
    The unified aggregation of all executing methodologies, generated by the MethodologyConsensusEngine.
    Highlights agreements, contradictions, and statistical confidence spreads across the ecosystem.
    Consumed by Platform 11.
    """
    dominant_hypotheses: List[str] = field(default_factory=list)
    agreement_clusters: Dict[str, List[str]] = field(default_factory=dict)
    unresolved_conflicts: List[str] = field(default_factory=list)
    probabilities: Dict[str, float] = field(default_factory=dict) # e.g. {"Bullish": 0.65, "Distribution": 0.35}
    uncertainty_score: float = 0.0
    active_methodology_count: int = 0
