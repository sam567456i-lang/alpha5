from dataclasses import dataclass, field
from typing import List, Dict, Optional, Any
from enum import Enum

class ProvenanceType(Enum):
    DIRECT = "DIRECT"
    INFERRED = "INFERRED"

@dataclass(frozen=True)
class ProvenanceScore:
    """Tracks how much of the evidence was directly observed vs statistically inferred."""
    direct_weight: float
    inferred_weight: float
    
    def __post_init__(self):
        if not (0.0 <= self.direct_weight <= 1.0) or not (0.0 <= self.inferred_weight <= 1.0):
            raise ValueError("Provenance weights must be between 0.0 and 1.0")

@dataclass(frozen=True)
class RuleEvidence:
    """The rich output generated by an Evidence Rule instead of a boolean."""
    rule_name: str
    rule_version: str
    confidence: float
    provenance: ProvenanceScore
    supporting_uuids: List[str]
    contradicting_uuids: List[str]
    metadata: Dict[str, Any] = field(default_factory=dict)
