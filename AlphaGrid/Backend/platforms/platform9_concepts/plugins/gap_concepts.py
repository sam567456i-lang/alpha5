import yaml
import os
from typing import List, Any
from Backend.platforms.platform9_concepts.concept_framework import ConceptPlugin
from Backend.platforms.platform9_concepts.concept_base import BaseConcept, ConceptID, ConceptCategory, ConceptType
from Backend.platforms.platform9_concepts.zone_features import ZoneFeature
from Backend.platforms.platform9_concepts.semantic_evidence import SemanticEvidence
from Backend.core.state import ExecutionContext

class FVGConceptPlugin(ConceptPlugin):
    """
    Evaluates ZoneFeatures generated by GAP_ZONEs to produce FVGConcepts.
    Strictly depends on the zone_capability_registry for valid mapping.
    """
    def __init__(self):
        super().__init__()
        self._load_capability_mapping()

    def _load_capability_mapping(self):
        registry_path = os.path.join(
            os.path.dirname(__file__), 
            "..", "..", "..", "..", "Docs", "Governance", "registry", "zone_capability_registry.yaml"
        )
        with open(registry_path, 'r', encoding='utf-8') as f:
            data = yaml.safe_load(f)
            self.fvg_mapping = data.get("capabilities", {}).get("CAP-FVG-01", {})
            self.base_zone_type = self.fvg_mapping.get("base_zone_type", "GAP_ZONE")

    def extract(self, features: List[Any], context: ExecutionContext) -> List[BaseConcept]:
        concepts = []
        for feature in features:
            if not isinstance(feature, ZoneFeature):
                continue
                
            zone = feature.zone_dto
            
            # 1. Registry Mapping Check: Does this zone type support FVG?
            if zone.identity.zone_type != self.base_zone_type:
                # Invalid mapping scenario
                continue
                
            # 2. Semantic Evaluation
            # Instead of recalculating geometry, we just assert properties
            is_bullish = zone.geometry.upper_price > zone.geometry.lower_price
            
            # Evidence collection
            evidence = SemanticEvidence(
                evidence_id=f"EVID-FVG-{zone.identity.zone_id}",
                criteria_met=["imbalance", "displacement"],
                supporting_metrics={"latency": zone.metadata.latency_ms},
                supporting_zone_id=zone.identity.zone_id,
                detector_version=zone.metadata.registry_version
            )
            
            c_id = ConceptID(
                category=ConceptCategory.SPATIAL,
                type=ConceptType.FAIR_VALUE_GAP,
                capability_id="CAP-FVG-01",
                ontology_id=zone.identity.ontology_id,
                version="1.0.0"
            )
            
            concept = BaseConcept(
                concept_id=c_id,
                source_features=[feature],
                semantic_evidence=evidence,
                description=f"{'Bullish' if is_bullish else 'Bearish'} Fair Value Gap",
                context=context
            )
            concepts.append(concept)
            
        return concepts
