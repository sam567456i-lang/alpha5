import os
from typing import List, Dict, Any
from ProjectOS.registry.parser import RegistryParser

class CapabilityMatrixGenerator:
    """Project OS Capability Engine - Generates the Master Capability Matrix"""
    
    def __init__(self, repo_root: str):
        self.repo_root = repo_root
        self.registry_parser = RegistryParser(repo_root)
        self.output_path = os.path.join(repo_root, "Docs", "Governance", "Master_Capability_Matrix.md")
        
    def generate_matrix(self) -> str:
        """Deterministically generates the Master Capability Matrix."""
        capabilities = self.registry_parser.get_capabilities()
        
        headers = [
            "Capability ID", "Name", "Platform", "Program", "Project", "Family", "Plugin",
            "Feature", "Concept", "Methodology", "Signal", "Markets", "Asset Classes", "Exchanges",
            "Timeframes", "Trading Styles", "Inputs", "Outputs", "Dependencies", "DTO",
            "ExecutionContext", "Registry Entry", "Validators", "Documentation", "Dashboard Integration",
            "AI Integration", "Research Integration", "Notification Integration", "Universal Switch",
            "Version", "Lifecycle", "Status", "Freeze State"
        ]
        
        lines = []
        lines.append("# AlphaGrid Master Capability Matrix")
        lines.append("\n> **GENERATED ARTIFACT**: Do not edit manually. Generated by Project OS.\n")
        
        lines.append("| " + " | ".join(headers) + " |")
        lines.append("|" + "|".join(["---"] * len(headers)) + "|")
        
        for cap in capabilities:
            row = []
            # Extract standard fields or default to 'N/A'
            row.append(cap.get("id", "N/A"))
            row.append(cap.get("name", "N/A"))
            row.append(cap.get("platform", "N/A"))
            row.append(cap.get("program", "N/A"))
            row.append(cap.get("project", "N/A"))
            row.append(cap.get("family", "N/A"))
            row.append(cap.get("plugin", "N/A"))
            
            # Fill the rest of the 33 columns with Placeholders or extracted data
            for _ in range(7, len(headers)):
                row.append("TBD")
            
            lines.append("| " + " | ".join(row) + " |")
            
        markdown_content = "\n".join(lines)
        
        os.makedirs(os.path.dirname(self.output_path), exist_ok=True)
        with open(self.output_path, "w", encoding="utf-8") as f:
            f.write(markdown_content)
            
        return markdown_content

