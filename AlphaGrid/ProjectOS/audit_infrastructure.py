import os
import re

class InfrastructureAuditor:
    def __init__(self, repo_root: str):
        self.repo_root = repo_root
        self.backend = os.path.join(repo_root, "Backend")
        
        self.findings = {
            "Canonical Domain Model": [],
            "Event Architecture": [],
            "Plugin SDK": [],
            "Data Quality Framework": [],
            "Observability Framework": []
        }

    def scan_directory(self):
        for root, dirs, files in os.walk(self.backend):
            for file in files:
                if not file.endswith(".py"):
                    continue
                    
                path = os.path.join(root, file)
                try:
                    with open(path, 'r', encoding='utf-8') as f:
                        content = f.read()
                        
                        # 1. Domain Models (DTOs)
                        if "dataclass" in content and "dto" in file.lower():
                            self.findings["Canonical Domain Model"].append(path)
                            
                        # 2. Events
                        if "Event" in content or "emit" in content or "publish" in content:
                            if "event" in file.lower():
                                self.findings["Event Architecture"].append(path)
                                
                        # 3. Plugin SDK
                        if "ABC" in content or "abstractmethod" in content or "Plugin" in content:
                            if "plugin" in file.lower() or "interface" in file.lower():
                                self.findings["Plugin SDK"].append(path)
                                
                        # 4. Data Quality
                        if "validate" in file.lower() or "clean" in file.lower() or "quality" in file.lower():
                            self.findings["Data Quality Framework"].append(path)
                            
                        # 5. Observability
                        if "log" in file.lower() or "metric" in file.lower() or "perf" in file.lower() or "timer" in file.lower():
                            self.findings["Observability Framework"].append(path)
                except Exception:
                    pass

    def generate_report(self):
        report_path = os.path.join(self.repo_root, "Docs", "Governance", "Infrastructure_Classification_Report.md")
        
        lines = [
            "# Infrastructure Classification Report",
            "*(Generated by Phase 1A: Canonical Architecture Validation)*\n",
            "This report audits the repository for existing fragments of the 5 mandatory infrastructure frameworks prior to formal specification.\n"
        ]
        
        for category, paths in self.findings.items():
            lines.append(f"## {category}")
            if not paths:
                lines.append("**Status**: NOT IMPLEMENTED. Completely missing.")
                lines.append("**Classification**: `MIGRATE/NEW`")
                lines.append("**Missing Pieces**: Complete framework specification required.\n")
            else:
                lines.append("**Status**: PARTIALLY IMPLEMENTED (Scattered fragments detected).")
                lines.append("**Fragments Found:**")
                for p in paths[:5]: # limit to top 5
                    rel = os.path.relpath(p, self.repo_root)
                    lines.append(f"- `{rel}`")
                if len(paths) > 5:
                    lines.append(f"- ... and {len(paths)-5} more.")
                lines.append("\n**Classification**: `REUSE / EXTEND`")
                lines.append("**Missing Pieces**: Needs centralized specification, governance registry, and formal contracts.\n")
                
        with open(report_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))
            
        print(f"Audit complete. Classification Report written to: {report_path}")

