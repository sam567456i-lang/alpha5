"""Concept state enumerations."""

from enum import StrEnum

class MomentumState(StrEnum):
    INCREASING = "INCREASING"
    WEAKENING = "WEAKENING"
    EXHAUSTED = "EXHAUSTED"
    ACCELERATING = "ACCELERATING"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"

class VolatilityState(StrEnum):
    EXPANDING = "EXPANDING"
    CONTRACTING = "CONTRACTING"
    NORMAL = "NORMAL"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"

class ExtremumState(StrEnum):
    OVEREXTENDED_BULLISH = "OVEREXTENDED_BULLISH"
    OVEREXTENDED_BEARISH = "OVEREXTENDED_BEARISH"
    NEUTRAL = "NEUTRAL"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"

class TrendState(StrEnum):
    BULLISH = "BULLISH"
    BEARISH = "BEARISH"
    RANGE_BOUND = "RANGE_BOUND"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"

class BreakoutState(StrEnum):
    BULLISH_BREAKOUT = "BULLISH_BREAKOUT"
    BEARISH_BREAKOUT = "BEARISH_BREAKOUT"
    NO_BREAKOUT = "NO_BREAKOUT"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"

class StrengthState(StrEnum):
    WEAK = "WEAK"
    MODERATE = "MODERATE"
    STRONG = "STRONG"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"

class VolumeState(StrEnum):
    ACCUMULATION = "ACCUMULATION"
    DISTRIBUTION = "DISTRIBUTION"
    SURGE = "SURGE"
    CLIMAX = "CLIMAX"
    NORMAL = "NORMAL"
    UNKNOWN = "UNKNOWN"
    WARMING_UP = "WARMING_UP"
